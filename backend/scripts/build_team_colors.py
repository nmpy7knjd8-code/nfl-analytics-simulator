"""Build frontend/lib/teamColors.json from nflverse teams_colors_logos (team_color, team_color2, team_color3/4).

Colors only (no logo URLs). Keys are the 32 current nflverse team_abbr values the repo already uses
(e.g. LA for the Rams, LV, WAS); historical/alias rows (LAR, OAK, SD, STL) are dropped.
Run: python backend/scripts/build_team_colors.py
"""
from __future__ import annotations

import csv
import io
import json
import re
import urllib.request
from pathlib import Path

URL = "https://github.com/nflverse/nflverse-data/releases/download/teams/teams_colors_logos.csv"
OUT = Path(__file__).resolve().parents[2] / "frontend" / "lib" / "teamColors.json"
DROP = {"LAR", "OAK", "SD", "STL"}  # aliases / relocated franchises in the nflverse file
HEX = re.compile(r"^#[0-9A-F]{6}$")


def _rgb(h: str) -> tuple[int, int, int]:
    return int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)


def is_neutral(h: str) -> bool:
    """White, black or gray: channels within 16 of each other."""
    r, g, b = _rgb(h)
    return max(r, g, b) - min(r, g, b) <= 16


def near(a: str, b: str, tol: int = 40) -> bool:
    return sum((x - y) ** 2 for x, y in zip(_rgb(a), _rgb(b))) ** 0.5 <= tol


def pick_tertiary(abbr: str, p: str, s: str, c3: str, c4: str, notes: dict[str, str]) -> str:
    """team_color3, unless missing/neutral/duplicate; then team_color4 if it is a real distinct
    team color; otherwise keep nflverse's team_color3 (or team_color2 if color3 is blank). Never invented."""
    def bad(c: str) -> bool:  # color3 rule: missing, neutral, or an exact duplicate
        return not HEX.match(c) or is_neutral(c) or c in (p, s)

    def distinct(c: str) -> bool:  # color4 must be a real team color, not a shade of primary/secondary
        return bool(HEX.match(c)) and not is_neutral(c) and not near(c, p) and not near(c, s)

    if not bad(c3):
        return c3
    why = "missing" if not c3 else ("neutral" if is_neutral(c3) else "duplicates primary/secondary")
    if distinct(c4):
        notes[abbr] = f"team_color3 {c3 or '(blank)'} {why}; used team_color4 {c4}"
        return c4
    if HEX.match(c3):
        notes[abbr] = f"team_color3 {c3} {why}; team_color4 {c4 or '(blank)'} not distinct; kept team_color3"
        return c3
    notes[abbr] = f"team_color3/team_color4 blank in nflverse; used team_color2 {s}"
    return s


def main() -> None:
    text = urllib.request.urlopen(URL, timeout=60).read().decode("utf-8")
    teams: dict[str, dict[str, str]] = {}
    notes: dict[str, str] = {}
    for row in csv.DictReader(io.StringIO(text)):
        abbr = row["team_abbr"]
        if abbr in DROP:
            continue
        p, s = row["team_color"].upper(), row["team_color2"].upper()
        c3, c4 = row["team_color3"].strip().upper(), row["team_color4"].strip().upper()
        assert HEX.match(p) and HEX.match(s), (abbr, p, s)
        t = pick_tertiary(abbr, p, s, c3, c4, notes)
        teams[abbr] = {"primary": p, "secondary": s, "tertiary": t}
    assert len(teams) == 32, sorted(teams)
    doc = {
        "_source": f"nflverse teams_colors_logos ({URL}) team_color/team_color2/team_color3 "
        "(team_color4 when color3 is missing, neutral or a duplicate; see _tertiary_notes); "
        "generated by backend/scripts/build_team_colors.py — do not edit by hand",
        "_tertiary_notes": dict(sorted(notes.items())),
        "teams": dict(sorted(teams.items())),
    }
    OUT.write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {OUT} ({len(teams)} teams)")


if __name__ == "__main__":
    main()
