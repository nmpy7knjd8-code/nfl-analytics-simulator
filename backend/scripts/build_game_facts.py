"""Build frontend/lib/gameFacts.json from nflverse schedules (the only source of game facts).

Usage: python backend/scripts/build_game_facts.py [--check]

Only factual columns are copied (no odds / lines). ``--check`` exits non-zero if the
committed file differs from nflverse — the same comparison CI runs in tests/test_game_facts.py.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FACTS_PATH = REPO / "frontend" / "lib" / "gameFacts.json"

# Games the fan UI demos. Add an id here, rerun, commit the JSON.
FIXTURE_GAME_IDS: tuple[str, ...] = ("2023_01_DET_KC", "2023_01_BUF_NYJ", "2023_03_PHI_TB")

# Whitelist: facts only. Never copy moneyline / spread / total columns.
FACT_COLUMNS = ("game_id", "season", "game_type", "week", "gameday", "home_team", "away_team",
                "home_score", "away_score", "overtime", "stadium")


def facts_from_schedules(schedules, game_ids=FIXTURE_GAME_IDS) -> list[dict]:
    rows = schedules[schedules["game_id"].isin(list(game_ids))]
    missing = set(game_ids) - set(rows["game_id"])
    if missing:
        raise ValueError(f"not in nflverse schedules: {sorted(missing)}")
    by_id = {r["game_id"]: r for r in rows[list(FACT_COLUMNS)].to_dict("records")}
    out = []
    for gid in game_ids:
        r = by_id[gid]
        out.append({
            "game_id": gid,
            "season": int(r["season"]),
            "week": int(r["week"]),
            "season_type": "REG" if r["game_type"] == "REG" else "POST",
            "game_date": str(r["gameday"]),
            "home_team_id": r["home_team"],
            "away_team_id": r["away_team"],
            "home_score": int(r["home_score"]),
            "away_score": int(r["away_score"]),
            "overtime": bool(int(r["overtime"])),
            "stadium": r["stadium"],
        })
    return out


def load_nflverse_schedules(seasons):
    import nflreadpy as nfl
    return nfl.load_schedules(sorted(set(seasons))).to_pandas()


def render(facts: list[dict]) -> str:
    doc = {"_source": "nflverse schedules via nflreadpy; generated by backend/scripts/build_game_facts.py — do not edit by hand",
           "games": facts}
    return json.dumps(doc, indent=2) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    seasons = [int(g[:4]) for g in FIXTURE_GAME_IDS]
    text = render(facts_from_schedules(load_nflverse_schedules(seasons)))
    if a.check:
        ok = FACTS_PATH.exists() and FACTS_PATH.read_text() == text
        print("gameFacts.json matches nflverse" if ok else "gameFacts.json is OUT OF DATE vs nflverse")
        return 0 if ok else 1
    FACTS_PATH.write_text(text)
    print(f"wrote {FACTS_PATH.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
